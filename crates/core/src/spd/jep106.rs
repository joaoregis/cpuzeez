/// Name for a 1-based bank and code byte (the parity bit is ignored).
pub fn name(bank: u8, code: u8) -> Option<&'static str> {
    let c = code & 0x7F;
    if c == 0 || c == 0x7F {
        return None;
    }
    match bank {
        1 => Some(BANK1[c as usize - 1]),
        2 => Some(BANK2[c as usize - 1]),
        _ => OTHER.iter().find(|e| e.0 == bank && e.1 == c).map(|e| e.2),
    }
}

#[cfg(test)]
mod tests {
    #[test]
    fn lookup() {
        assert_eq!(super::name(1, 0xAD), Some("SK Hynix"));
        assert_eq!(super::name(1, 0xCE), Some("Samsung"));
        assert_eq!(super::name(1, 0x2C), Some("Micron Technology"));
        assert_eq!(super::name(2, 0x98), Some("Kingston"));
        assert_eq!(super::name(5, 0xEF), Some("TEAMGROUP Inc."));
        assert_eq!(super::name(11, 0x8C), Some("Richtek Power"));
        assert_eq!(super::name(9, 0x01), None);
    }
}
