//! MangoHud integration, the pure parts (S2b-06, docs/v1/zeez-live.md §3.1
//! Q4): the config CpuZeeZ generates from the user's overlay layout, the
//! `environment.d` file that enables it for every game, and the package
//! manager command that installs it.

use crate::layout::Layout;
use crate::live::Anchor;

/// The file that enables MangoHud for all games (opt-in; deleting it undoes it).
pub const ENV_FILE: &str = "cpuzeez-mangohud.conf";
/// Our MangoHud config, next to (never over) the user's own MangoHud.conf.
pub const CONFIG_FILE: &str = "cpuzeez.conf";
/// What Steam's launch options take, per game.
pub const LAUNCH_OPTION: &str = "mangohud %command%";
pub const FLATPAK_ID: &str = "org.freedesktop.Platform.VulkanLayer.MangoHud";

/// `~/.config/environment.d/cpuzeez-mangohud.conf`.
pub fn env_file(config: &str) -> String {
    format!(
        "# Written by CpuZeeZ (ZeeZ Live). Delete this file to stop enabling MangoHud for every game.\nMANGOHUD=1\nMANGOHUD_CONFIGFILE={config}\n"
    )
}

fn position(a: Anchor) -> &'static str {
    match a {
        Anchor::TopLeft | Anchor::Left => "top-left",
        Anchor::Top | Anchor::Center => "top-center",
        Anchor::TopRight | Anchor::Right => "top-right",
        Anchor::BottomLeft => "bottom-left",
        Anchor::Bottom => "bottom-center",
        Anchor::BottomRight => "bottom-right",
    }
}

/// MangoHud's options for our layout's metrics, plus per-frame logging into
/// `log_dir` (what CpuZeeZ reads back for FPS, captures and reports).
pub fn config(l: &Layout, anchor: Anchor, log_dir: &str) -> String {
    let m = l.metrics();
    let has = |needle: &str| m.iter().any(|x| x.contains(needle));
    let mut opts: Vec<&str> = vec!["legacy_layout=0"];
    if has("frames/fps") || has("frames/low") {
        opts.push("fps");
    }
    if has("frames/ms") {
        opts.extend(["frametime", "frame_timing=1"]);
    }
    if has("@cpu_load") || has("@cpu_max_core") {
        opts.push("cpu_stats");
    }
    if has("@cpu_temp") {
        opts.push("cpu_temp");
    }
    if has("@cpu_power") {
        opts.push("cpu_power");
    }
    if has("@gpu_load") {
        opts.push("gpu_stats");
    }
    if has("@gpu_temp") {
        opts.push("gpu_temp");
    }
    if has("@gpu_power") {
        opts.push("gpu_power");
    }
    if has("@gpu_clock") {
        opts.push("gpu_core_clock");
    }
    if has("@mem_load") {
        opts.push("ram");
    }
    if opts.len() == 1 {
        opts.push("fps");
    }
    let mut s = String::from("# Generated by CpuZeeZ from your ZeeZ Live layout. Changes here are replaced.\n");
    for o in opts {
        s += o;
        s.push('\n');
    }
    s += &format!("position={}\n", position(anchor));
    s += &format!("output_folder={log_dir}\nlog_interval=0\nautostart_log=1\ntoggle_logging=Shift_L+F2\n");
    s
}

/// The command that installs MangoHud with `manager` (run through pkexec).
pub fn install_command(manager: &str) -> Option<Vec<&'static str>> {
    Some(match manager {
        "apt" => vec!["apt-get", "install", "-y", "mangohud"],
        "dnf" => vec!["dnf", "install", "-y", "mangohud"],
        "pacman" => vec!["pacman", "-S", "--noconfirm", "mangohud"],
        "zypper" => vec!["zypper", "--non-interactive", "install", "mangohud"],
        _ => return None,
    })
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn config_follows_the_layout() {
        let c = config(&crate::layout::presets::live::compact(95.0), Anchor::BottomRight, "/tmp/logs");
        for want in [
            "fps\n",
            "gpu_temp\n",
            "cpu_temp\n",
            "ram\n",
            "position=bottom-right\n",
            "output_folder=/tmp/logs\n",
            "autostart_log=1\n",
        ] {
            assert!(c.contains(want), "missing {want:?} in\n{c}");
        }
        assert!(!c.contains("frametime"), "Compact has no frame-time graph");
        let b = config(&crate::layout::presets::live::benchmark(), Anchor::TopLeft, "/x");
        assert!(b.contains("frame_timing=1"));
        assert!(
            env_file("/h/.config/MangoHud/cpuzeez.conf")
                .contains("MANGOHUD=1\nMANGOHUD_CONFIGFILE=/h/.config/MangoHud/cpuzeez.conf\n")
        );
        assert_eq!(install_command("pacman").unwrap()[0], "pacman");
        assert!(install_command("emerge").is_none());
    }
}
